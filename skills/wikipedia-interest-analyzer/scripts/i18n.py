"""Report language: the English message catalog, the loader, the translator.

Every user-facing string the report and the chart print -- headings, table
headers, captions, the headline sentence, assumptions and limitations -- is
declared in :data:`MESSAGES` as an **English template keyed by a stable id**.

To produce a report in *any* language, an agent writes a JSON file that maps
each id to that language's wording (the English template is the reference:
translate the words, keep the ids and the ``{placeholders}``) and renders with
``--report-lang <code>``. Nothing is machine-translated inside the skill, so a
translation can never be invented silently.

What this module guarantees:

* an id that is not in :data:`MESSAGES` raises ``KeyError`` -- a typo fails
  loudly instead of printing English nobody checked;
* a translation whose ``{placeholders}`` differ from the English template is
  **rejected** (recorded as invalid) and the English text is used instead, so
  a dropped ``{count}`` cannot produce ``"shown: "`` ;
* every fallback is recorded and *reported*: :meth:`Translator.note` renders a
  visible note for the report, :func:`warn_untranslated` prints the full id
  list to stderr.

Data is never translated: numbers, month labels, language codes, article
titles, Q-ids and message ids are passed in already formatted by the stage
that computed them.
"""

